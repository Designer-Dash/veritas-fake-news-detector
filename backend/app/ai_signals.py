"""AI-content and provenance signal checks.

Covers, in order of practical reliability today:
  1. C2PA / Content Credentials metadata (IPTC "Digital Source Type" news codes)
  2. Known generative-AI watermark/exif markers (SynthID text markers, tool strings)
  3. C2PA manifest presence in JPEG bytes (JUMBF box scan)
  4. Missing provenance on high-risk media-heavy pages (advisory only)
"""

from __future__ import annotations

import re
from typing import Any, Dict, List

# IPTC Digital Source Type news codes -- the industry standard for declaring
# how media was created (https://iptc.org/standards/photo-metadata/).
DIGITAL_SOURCE_TYPES = {
    "digitalCapture": ("Original camera capture", -0.3),
    "negativeFilm": ("Scanned from film", -0.2),
    "minorHumanEdited": ("Minor human edits", -0.2),
    "majorHumanEdited": ("Major human edits", 0.0),
    "algorithmicMedia": ("Fully generated by an algorithm (AI)", 0.5),
    "algorithmicMediaWithHumanReview": ("AI-generated, human reviewed", 0.25),
    "compositeWithTrainedAlgorithmicMedia": ("Composite containing AI media", 0.35),
    "dataDrivenMedia": ("Data-plot / chart render", -0.1),
    "digitalArt": ("Digital art (non-photo)", 0.0),
    "screenCapture": ("Screen capture", -0.1),
    "composite": ("Composite of captures", -0.1),
    "compositeSynthography": ("Composite with synthetic video", 0.4),
    "trainedAlgorithmicMedia": ("AI-trained media", 0.5),
}

# Strings found in EXIF/XMP of common generators.
TOOL_MARKERS = {
    "midjourney": "Midjourney",
    "stable-diffusion": "Stable Diffusion",
    "stable diffusion": "Stable Diffusion",
    "dall-e": "DALL-E",
    "dall·e": "DALL-E",
    "openai": "OpenAI tooling",
    "synthid": "Google SynthID",
    "firefly": "Adobe Firefly",
    "sd-webui": "Stable Diffusion WebUI",
    "comfyui": "ComfyUI",
    "flux.1": "FLUX",
    "runwayml": "Runway",
    "sora": "OpenAI Sora",
    "gemini": "Google Gemini",
}

C2PA_MARKERS = ("c2pa", "jumbf", "urn:uuid:", "contentcredentials")

SYNTHID_TEXT_MARKERS = (
    # SynthID for text embeds statistical watermarks, not literal strings; these
    # byte patterns appear in some payloads/metadata exports.
    "\u200b",  # zero-width space runs
    "\u2060",  # word joiner
)


def scan_bytes(data: bytes) -> Dict[str, Any]:
    """Scan raw media bytes (JPEG/PNG/WebP) for provenance markers."""
    head = data[:262144]  # metadata lives near the start
    try:
        text = head.decode("latin-1", errors="ignore").lower()
    except Exception:  # pragma: no cover
        text = ""

    result: Dict[str, Any] = {
        "has_c2pa": any(m in text for m in C2PA_MARKERS),
        "tool_markers": sorted({name for needle, name in TOOL_MARKERS.items() if needle in text}),
        "digital_source_type": None,
        "synthid_markers": sum(text.count(m) for m in SYNTHID_TEXT_MARKERS),
    }

    dst = re.search(r"digitalSourceType[^A-Za-z]*([A-Za-z]+)", text)
    if dst and dst.group(1) in DIGITAL_SOURCE_TYPES:
        result["digital_source_type"] = dst.group(1)
    return result


def scan_html_for_media_flags(html: str) -> Dict[str, Any]:
    """Look at <img>/<meta> tags for provenance hints without fetching media."""
    meta_blob = " ".join(re.findall(r"<meta[^>]+>", html, flags=re.IGNORECASE)).lower()
    tool_markers = sorted({name for needle, name in TOOL_MARKERS.items() if needle in meta_blob})
    has_c2pa = any(m in meta_blob for m in C2PA_MARKERS)
    img_count = len(re.findall(r"<img\b", html, flags=re.IGNORECASE))
    return {
        "has_c2pa": has_c2pa,
        "tool_markers": tool_markers,
        "img_count": img_count,
    }


def score_media_signals(byte_scan: Dict[str, Any], html_scan: Dict[str, Any]) -> Dict[str, Any]:
    """Merge byte-level and HTML-level media findings into one assessment."""
    dst = byte_scan.get("digital_source_type")
    label, dst_weight = DIGITAL_SOURCE_TYPES.get(dst, (None, 0.0))

    tools = sorted(set(byte_scan.get("tool_markers", [])) | set(html_scan.get("tool_markers", [])))
    has_c2pa = bool(byte_scan.get("has_c2pa") or html_scan.get("has_c2pa"))
    synthid_hits = int(byte_scan.get("synthid_markers", 0))

    weight = dst_weight
    reasons: List[str] = []
    if dst:
        reasons.append(label or dst)

    if tools:
        weight = max(weight, 0.45)
        reasons.append("Generator tool markers: " + ", ".join(tools))

    if has_c2pa:
        # A manifest exists; if it wasn't already negative via DST, credit it.
        weight = min(weight if weight > 0 else -0.2, 0.0) if dst else -0.2
        reasons.append("C2PA Content Credentials manifest present")

    if synthid_hits >= 3:
        weight = max(weight, 0.4)
        reasons.append("Invisible-watermark byte pattern consistent with SynthID")

    return {
        "weight": weight,
        "reasons": reasons,
        "has_c2pa": has_c2pa,
        "tool_markers": tools,
        "digital_source_type": dst,
        "synthid_markers": synthid_hits,
    }
